#program to find quotient and reminder of two numbers
# Take input num1 and num2
num1 = int(input('Enter 1st number'))
num2 = int(input('Enter 2nd number'))

# perform operation
quotient= num1 // num2
reminder = num1 % num2

# Display result
print (f'quotient of two numbers is {quotient}')
print(f'reminder of two numbers id {reminder}')

