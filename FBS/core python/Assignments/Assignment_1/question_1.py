# Write a program to calculate the percentage of student based on marks of any 5 sunject

# 5 subject marks
sub1 = 85
sub2 = 88
sub3 = 90
sub4 = 95
sub5 = 100

# calculate total marks

total = sub1 + sub2 + sub3 + sub4 + sub5

# calculate percentage

per = (total / 500) * 100

print (f'percentage of student based on any 5 subject is {per}')